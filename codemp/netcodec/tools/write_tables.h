// Writes trained tables as a generated source (src/generated/jka_tables.inc, jka_client_tables.inc): for every
// context of [first, last) with at least one symbol counted, the quantised table of its counts.
#pragma once

#include "netcodec/codec.h"

#include <cstdio>
#include <memory>
#include <vector>

namespace netcodec::tools {

struct TablesFile {
	const char *tool;     // the generating program
	const char *what;     // what the tables are
	const char *unit;     // what was counted (messages, packets)
	const char *prefix;   // of the array names
};

inline bool WriteTables(const char *path, const SymbolCounts &counts, size_t items, const TablesFile &t, uint32_t first,
                        uint32_t last) {
	std::vector<uint32_t> contexts, starts{ 0 };
	std::vector<uint16_t> freq;
	for (uint32_t c = first; c < last && c < counts.symbols.size(); c++) {
		uint64_t n = 0;
		for (const uint64_t x : counts.symbols[c]) n += x;
		if (n == 0) continue;
		contexts.push_back(c);
		const size_t start = freq.size();
		freq.resize(start + counts.symbols[c].size());
		Quantize(counts.symbols[c], std::span<uint16_t>(freq).subspan(start));
		starts.push_back(ToU32(freq.size()));
	}
	const std::unique_ptr<FILE, int (*)(FILE *)> file(std::fopen(path, "wb"), &std::fclose);
	if (!file) { std::fprintf(stderr, "cannot write %s\n", path); return false; }
	FILE *f = file.get();
	std::fprintf(f, "// Generated by %s: do not edit.\n", t.tool);
	std::fprintf(f, "// %s (15-bit probabilities), %zu training %s: context %sContext[t] has\n", t.what, items, t.unit, t.prefix);
	std::fprintf(f, "// the frequencies %sFreq[%sStart[t] .. %sStart[t + 1]); the other contexts are uniform.\n\n", t.prefix,
	             t.prefix, t.prefix);
	std::fprintf(f, "inline constexpr uint32_t %sCount = %zu;\n", t.prefix, contexts.size());
	const auto list = [f, &t](const char *type, const char *name, const auto &v) {
		std::fprintf(f, "inline constexpr std::array<%s, %zu> %s%s{", type, v.size(), t.prefix, name);
		for (size_t i = 0; i < v.size(); i++) {
			const unsigned x = v[i];   // uint16_t or uint32_t
			std::fprintf(f, "%s%u%s", i % 24 == 0 ? "\n\t" : " ", x, i + 1 < v.size() ? "," : "");
		}
		std::fprintf(f, "\n};\n");
	};
	list("uint32_t", "Context", contexts);
	list("uint32_t", "Start", starts);
	list("uint16_t", "Freq", freq);
	std::printf("wrote %s: %zu trained contexts, %zu frequencies\n", path, contexts.size(), freq.size());
	return std::ferror(f) == 0;
}

} // namespace netcodec::tools
